#!/usr/bin/env python3
"""Bundle our deliberately small named-import modules for Safari's classic background page.

This is not a general JavaScript compiler. Unsupported module syntax fails the build.
The panel keeps using native ES modules. No npm/build dependency is required.
"""
from pathlib import Path
import json
import re
import sys

root = Path(__file__).resolve().parents[1] / "extension"
imports = re.compile(r'^import\s+\{([^}]+)\}\s+from\s+[\'"]([^\'"]+)[\'"];\s*$', re.M)
exports = re.compile(r'\bexport\s+(?:async\s+)?(?:function\*?|const|let|class)\s+(\w+)')
done = set()
visiting = set()
output = ["// Generated by scripts/bundle-background.py. Edit the source modules, not this file.\n(() => {\nconst modules = Object.create(null);\n"]

def visit(filename):
    filename = filename.resolve()
    key = filename.relative_to(root).as_posix()
    if key in done: return
    if key in visiting: raise ValueError(f"Circular background module dependency: {key}")
    visiting.add(key)
    source = filename.read_text(encoding="utf-8")
    for _, target in imports.findall(source):
        if not target.startswith("."): raise ValueError("Only local dependencies are supported")
        visit(filename.parent / target)
    names = exports.findall(source)
    source = imports.sub(lambda m: "const {" + m[1] + "} = modules[" + json.dumps((filename.parent / m[2]).resolve().relative_to(root).as_posix()) + "];", source)
    source = re.sub(r'\bexport\s+(?=(?:async\s+)?(?:function\*?|const|let|class)\s)', '', source)
    if re.search(r'^\s*(?:import|export)\b', source, re.M): raise ValueError(f"Unsupported module syntax in {key}")
    output.append(f"\n// {key}\nmodules[{json.dumps(key)}] = (() => {{\n{source}\nreturn {{{', '.join(names)}}};\n}})();\n")
    visiting.remove(key)
    done.add(key)

visit(root / "background.js")
output.append("})();\n")
bundle = "".join(output)
# Safari's generated classic background page can use a legacy script encoding.
# ASCII source with JavaScript Unicode escapes preserves the intended characters.
if not bundle.isascii():
    raise SystemExit("Use JavaScript Unicode escapes for non-ASCII characters in background source modules.")
destination = root / "background.bundle.js"
if "--check" in sys.argv:
    if not destination.exists() or destination.read_text(encoding="utf-8") != bundle: raise SystemExit("Background bundle is stale. Run python3 scripts/bundle-background.py.")
else:
    destination.write_text(bundle, encoding="ascii")
    print(f"Bundled {len(done)} background modules ({len(bundle.encode())} bytes).")
